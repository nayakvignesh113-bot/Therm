"""Regenerate sw.js with the full precache list. Run from the site root after every change."""
import os, hashlib, json
files, h = [], hashlib.sha256()
for root, dirs, fs in os.walk('.'):
    dirs[:] = [d for d in dirs if d not in ('.git', 'tools')]
    for f in sorted(fs):
        p = os.path.join(root, f)[2:]
        if p in ('sw.js', 'README.md', '.nojekyll') or p.endswith('.py'): continue
        files.append(p); h.update(open(p, 'rb').read())
ver = h.hexdigest()[:10]
open('sw.js', 'w').write(f"""/* generated by tools/build_sw.py — offline cache for the whole site */
const VERSION = 'thm-{ver}';
const FILES = {json.dumps(['./'] + sorted(files))};
self.addEventListener('install', e => e.waitUntil(caches.open(VERSION).then(c => c.addAll(FILES)).then(() => self.skipWaiting())));
self.addEventListener('activate', e => e.waitUntil(caches.keys().then(ks => Promise.all(ks.filter(k => k !== VERSION).map(k => caches.delete(k)))).then(() => self.clients.claim())));
self.addEventListener('fetch', e => {{
  if (e.request.method !== 'GET' || new URL(e.request.url).origin !== location.origin) return;
  e.respondWith(caches.match(e.request, {{ ignoreSearch: true }}).then(r => r || fetch(e.request).then(res => {{ const c = res.clone(); caches.open(VERSION).then(ca => ca.put(e.request, c)); return res; }}).catch(() => caches.match('./index.html'))));
}});
self.addEventListener('message', e => {{ if (e.data === 'version') e.source.postMessage({{ version: VERSION, files: FILES.length }}); }});
""")
print(ver, len(files), 'files')
